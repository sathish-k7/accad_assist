@router.post("/summary/pdf")
async def export_summary_to_pdf(
    text: str = Form(...),
    summary_type: SummaryType = Form(SummaryType.PARAGRAPH),
    summary_length: SummaryLength = Form(SummaryLength.MEDIUM),
    ai_model: AIModel = Form(AIModel.GPT_35_TURBO),
    focus_areas: Optional[str] = Form(None)
):
    """
    Summarize text content and export results to PDF format.
    
    This endpoint combines summarization with PDF export functionality:
    - Processes text using the specified AI model
    - Generates summary based on type and length preferences
    - Creates a formatted PDF report with results
    """
    try:
        start_time = time.time()
        
        # Validate input
        if not text or not text.strip():
            raise HTTPException(status_code=400, detail="Text content cannot be empty")
        
        if len(text) > 50000:  # Reasonable limit for text processing
            raise HTTPException(status_code=413, detail="Text content too long. Maximum 50,000 characters.")
        
        logger.info(f"Processing text summarization for PDF export using {ai_model.value}")
        
        # Mock summarization process (in real implementation, this would call the actual AI service)
        await asyncio.sleep(1.5)  # Simulate processing time
        
        # Generate mock summary based on parameters
        word_count = len(text.split())
        
        if summary_type == SummaryType.BULLET_POINTS:
            summary = (
                "• Main concepts and ideas from the provided content\n"
                "• Key arguments and supporting evidence presented\n"
                "• Important findings and conclusions drawn\n"
                "• Relevant examples and case studies mentioned\n"
                "• Practical applications and implications discussed"
            )
        elif summary_type == SummaryType.BRIEF:
            summary = "This is a concise summary capturing the essential points from the content, highlighting the main arguments, key findings, and practical implications in a brief format."
        else:  # PARAGRAPH or other types
            summary = (
                "This comprehensive summary provides a detailed overview of the main content, "
                "incorporating the key concepts, arguments, and findings presented. The analysis "
                "covers the primary themes, supporting evidence, and practical applications "
                f"discussed in the original text. Generated using {ai_model.value} with "
                f"{summary_type.value} formatting and {summary_length.value} length."
            )
        
        summary_word_count = len(summary.split())
        processing_time = time.time() - start_time
        
        # Prepare result data for PDF export
        result_data = {
            'summary': summary,
            'original_length': word_count,
            'summary_length': summary_word_count,
            'compression_ratio': summary_word_count / word_count if word_count > 0 else 0,
            'processing_time': processing_time,
            'ai_model': ai_model.value,
            'key_points': [
                "Primary concept extraction and analysis",
                "Supporting evidence identification",
                "Practical application insights",
                "Conclusion and implications summary"
            ]
        }
        
        # Generate PDF content
        pdf_content = pdf_exporter.export_summary_results(result_data)
        filename = pdf_exporter.generate_filename("text_summary", "export")
        
        logger.info(f"Successfully generated PDF export: {filename}")
        
        return Response(
            content=pdf_content,
            media_type="application/pdf",
            headers={
                "Content-Disposition": f"attachment; filename={filename}",
                "Content-Length": str(len(pdf_content))
            }
        )
        
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Summary PDF export failed: {str(e)}")
        raise HTTPException(status_code=500, detail=f"Export failed: {str(e)}")

